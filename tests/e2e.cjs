const { chromium, devices } = require('playwright');
const S = process.argv[2] || require('path').join(__dirname, 'out'); require('fs').mkdirSync(S + '/shots', { recursive: true });
const BASE = process.env.BASE_URL || 'http://localhost:4173';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ ...devices['Pixel 7'] });
  const p = await ctx.newPage();
  const errs = [];
  p.on('pageerror', e => errs.push('pageerror: ' + e.message));
  p.on('console', m => m.type() === 'error' && errs.push('console: ' + m.text()));
  await p.goto(BASE + '/');
  await p.screenshot({ path: S + '/shots/01-onboarding.png' });
  await p.getByText('Essayer avec des exemples').click();
  await p.getByText('Qui êtes-vous ?').waitFor();
  await p.screenshot({ path: S + '/shots/02-who.png' });
  await p.locator('.item', { hasText: 'Sofiatou' }).click();
  for (const d of '1234') await p.locator('.numpad button', { hasText: new RegExp('^' + d + '$') }).click();
  await p.getByText('Nouvelle vente').first().waitFor();
  await p.waitForTimeout(500);
  await p.screenshot({ path: S + '/shots/03-home.png', fullPage: true });
  await p.goto(BASE + '/vendre');
  await p.waitForTimeout(500);
  await p.screenshot({ path: S + '/shots/04-sell.png' });
  await p.locator('.search input').fill('ciment 35');
  await p.locator('.ptile').first().click();
  await p.locator('.chip', { hasText: '20 sac' }).click();
  await p.screenshot({ path: S + '/shots/05-qty.png' });
  await p.locator('.sheet .btn.primary').click();
  await p.locator('.search input').fill('coude');
  await p.locator('.ptile').first().click();
  for (const d of '12') await p.locator('.sheet .numpad button', { hasText: new RegExp('^' + d + '$') }).click();
  await p.getByRole('button', { name: /^Prix/ }).click();
  for (const d of '200') await p.locator('.sheet .numpad button', { hasText: new RegExp('^' + d + '$') }).first().click();
  await p.locator('.sheet .btn.primary').click();
  await p.screenshot({ path: S + '/shots/06-cartbar.png' });
  await p.locator('.cartbar .btn.primary').click();
  await p.locator('.sheet .chip').nth(2).click();
  await p.screenshot({ path: S + '/shots/07-checkout.png' });
  await p.getByRole('button', { name: /Valider la vente/ }).click();
  await p.getByText('Vente enregistrée').first().waitFor();
  await p.screenshot({ path: S + '/shots/08-done.png' });
  // credit sale
  await p.getByRole('button', { name: /Nouvelle vente/ }).click();
  await p.locator('.search input').fill('fer 10');
  await p.locator('.ptile').first().click();
  await p.locator('.chip', { hasText: '50 barre' }).click();
  await p.locator('.sheet .btn.primary').click();
  await p.locator('.cartbar .btn.primary').click();
  await p.getByRole('button', { name: 'À crédit' }).click();
  await p.getByRole('button', { name: /Choisir le client/ }).click();
  await p.locator('.item', { hasText: 'M. Kossi' }).first().click();
  await p.getByRole('button', { name: /Valider la vente/ }).click();
  await p.getByText('Vente enregistrée').first().waitFor();
  await p.goto(BASE + '/clients'); await p.waitForTimeout(400);
  await p.screenshot({ path: S + '/shots/09-clients.png' });
  await p.locator('.item', { hasText: 'M. Kossi' }).first().click(); await p.waitForTimeout(400);
  await p.screenshot({ path: S + '/shots/10-client.png' });
  await p.goto(BASE + '/stock'); await p.waitForTimeout(400);
  await p.screenshot({ path: S + '/shots/11-stock.png' });
  await p.locator('.item').first().click(); await p.waitForTimeout(400);
  await p.screenshot({ path: S + '/shots/12-product.png', fullPage: true });
  await p.goto(BASE + '/plan'); await p.waitForTimeout(400);
  await p.locator('.search input').fill('coude');
  await p.waitForTimeout(300);
  await p.screenshot({ path: S + '/shots/13-plan.png', fullPage: true });
  await p.goto(BASE + '/inventaire'); await p.waitForTimeout(400);
  await p.getByText('Entrepôt ciment').click(); await p.waitForTimeout(500);
  await p.getByRole('button', { name: /C'est juste/ }).first().click();
  await p.screenshot({ path: S + '/shots/14-inventory.png' });
  await p.goto(BASE + '/ventes'); await p.waitForTimeout(400);
  await p.screenshot({ path: S + '/shots/15-sales.png', fullPage: true });
  // offline test
  await ctx.setOffline(true);
  await p.goto(BASE + '/vendre').catch(e => errs.push('offline nav: ' + e.message));
  await p.waitForTimeout(600);
  await p.screenshot({ path: S + '/shots/16-offline.png' });
  await ctx.setOffline(false);

  const d = await b.newContext({ viewport: { width: 1366, height: 860 } });
  const q = await d.newPage();
  q.on('pageerror', e => errs.push('desk pageerror: ' + e.message));
  await q.goto(BASE + '/');
  await q.getByText('Essayer avec des exemples').click();
  await q.locator('.item', { hasText: 'Sofiatou' }).click();
  for (const x of '1234') await q.locator('.numpad button', { hasText: new RegExp('^' + x + '$') }).click();
  await q.getByText('Nouvelle vente').first().waitFor(); await q.waitForTimeout(500);
  await q.screenshot({ path: S + '/shots/20-desk-home.png' });
  await q.goto(BASE + '/vendre'); await q.waitForTimeout(400);
  await q.locator('.ptile').nth(0).click(); await q.locator('.sheet .btn.primary').click();
  await q.locator('.ptile').nth(2).click(); await q.locator('.sheet .btn.primary').click();
  await q.screenshot({ path: S + '/shots/21-desk-sell.png' });
  await q.goto(BASE + '/stock'); await q.waitForTimeout(400);
  await q.screenshot({ path: S + '/shots/22-desk-stock.png' });
  await q.goto(BASE + '/rapports'); await q.waitForTimeout(500);
  await q.screenshot({ path: S + '/shots/23-desk-reports.png', fullPage: true });
  await q.goto(BASE + '/plan'); await q.waitForTimeout(400);
  await q.locator('.zone-r').nth(1).click(); await q.waitForTimeout(300);
  await q.screenshot({ path: S + '/shots/24-desk-plan.png' });
  await q.goto(BASE + '/parametres'); await q.waitForTimeout(400);
  await q.screenshot({ path: S + '/shots/25-desk-settings.png' });
  console.log('ERRORS:', errs.length ? errs.join('\n') : 'none');
  await b.close();
})().catch(e => { console.error('FAIL', e); process.exit(1); });
